/**
 * Доменна модель симулятора фізичних процесів.
 * Файл містить лише типи (без логіки), без жодного `any`.
 * Одиниці виміру: SI (метри, кілограми, секунди, радіани/градуси - див. суфікс Deg).
 */

// ---------------------------------------------------------------------------
// Базові типи
// ---------------------------------------------------------------------------

/** Двовимірний вектор (координати, швидкість, сила). */
export interface Vec2 {
  /** Горизонтальна компонента. */
  x: number;
  /** Вертикальна компонента. */
  y: number;
}

/**
 * Стани контролера симуляції (скінченний автомат).
 * Використовується в Діаграмі станів (Розділ 1) та в useReducer (Issue #4).
 *  - IDLE:    пресет ще не обрано;
 *  - READY:   пресет обрано, параметри валідні, симуляцію можна запускати;
 *  - RUNNING: симуляція виконується;
 *  - PAUSED:  симуляцію призупинено, стан збережено;
 *  - ERROR:   параметри або дані некоректні, потрібне виправлення.
 */
export type SimulationStatus = 'IDLE' | 'READY' | 'RUNNING' | 'PAUSED' | 'ERROR';

/** Ідентифікатори пресетів: балістика, пружні зіткнення, маятник. */
export type PresetId = 'PROJECTILE' | 'COLLISIONS' | 'PENDULUM';

/** Режим теми оформлення (Issue #3). */
export type ThemeMode = 'light' | 'dark';

// ---------------------------------------------------------------------------
// Пресети
// ---------------------------------------------------------------------------

/** Метадані пресету для відображення у списку вибору. */
export interface PresetMeta {
  /** Унікальний ідентифікатор (використовується як React key). */
  id: PresetId;
  /** Коротка назва для заголовка картки. */
  title: string;
  /** Опис фізичного процесу для підказки користувачу. */
  description: string;
  /** Основне фізичне співвідношення, що моделюється. */
  keyFormula: string;
  /** Кількість тіл у початковій сцені пресету. */
  bodiesCount: number;
}

// ---------------------------------------------------------------------------
// Тіла та параметри
// ---------------------------------------------------------------------------

/** Фізичне тіло (кулька, вантаж маятника, снаряд). */
export interface Body {
  /** Унікальний ідентифікатор (React key у списках). */
  id: string;
  /** Людиночитна мітка для UI та CSV. */
  label: string;
  /** Маса, кг. Має бути > 0 (перевіряється валідатором, Issue #4). */
  mass: number;
  /** Радіус, м. Має бути > 0. */
  radius: number;
  /** Коефіцієнт відновлення при зіткненнях, 0..1. */
  restitution: number;
  /** Колір відмальовування (CSS-колір). */
  color: string;
  /** Положення центра, м. */
  position: Vec2;
  /** Швидкість, м/с. */
  velocity: Vec2;
  /** Сумарна сила, що діє на тіло, Н (для візуалізації векторів сил). */
  force: Vec2;
  /** Слід траєкторії (обмежений за довжиною кільцевий буфер). */
  trail: Vec2[];
}

/** Параметри середовища, спільні для всіх пресетів. */
export interface EnvironmentParams {
  /** Прискорення вільного падіння, м/с^2. */
  gravity: number;
  /** Коефіцієнт опору середовища (демпфування), 1/с. */
  damping: number;
  /** Множник швидкості плину часу симуляції. */
  timeScale: number;
  /** Крок інтегрування, с. Обмежується зверху валідатором. */
  dt: number;
  /** Коефіцієнт відновлення при відбитті від стін, 0..1. */
  restitutionWall: number;
}

/** Специфічні параметри пресетів. */
export interface PresetParams {
  /** Кут пострілу над горизонтом, градуси (PROJECTILE). */
  launchAngleDeg: number;
  /** Початкова швидкість, м/с (PROJECTILE, COLLISIONS). */
  initialSpeed: number;
  /** Довжина підвісу, м (PENDULUM). */
  pendulumLength: number;
  /** Початковий кут відхилення від вертикалі, градуси (PENDULUM). */
  initialAngleDeg: number;
}

/** Повний набір параметрів, що редагуються користувачем. */
export type SimulationParams = EnvironmentParams & PresetParams;

// ---------------------------------------------------------------------------
// Телеметрія
// ---------------------------------------------------------------------------

/** Знімок телеметрії в один момент часу (рядок журналу та CSV). */
export interface TelemetrySnapshot {
  /** Час симуляції, с. */
  time: number;
  /** Сумарна кінетична енергія, Дж. */
  kineticEnergy: number;
  /** Сумарна потенціальна енергія, Дж. */
  potentialEnergy: number;
  /** Повна механічна енергія E = Ek + Ep, Дж. */
  totalEnergy: number;
  /** Поточна частота кадрів рендерера. */
  fps: number;
  /** Кількість тіл, що беруть участь у симуляції. */
  activeBodiesCount: number;
}

// ---------------------------------------------------------------------------
// Профіль дослідника (Issue #3) та експорт сцени (Issue #9)
// ---------------------------------------------------------------------------

/** Профіль дослідника, що зберігається в localStorage. */
export interface ResearcherProfile {
  /** Унікальний ідентифікатор профілю (ізолює дані різних дослідників). */
  id: string;
  /** Відображуване ім'я (після санітизації). */
  displayName: string;
  /** Дата створення, ISO 8601. */
  createdAt: string;
  /** Дата останнього входу, ISO 8601. */
  lastLoginAt: string;
  /** Обрана тема оформлення. */
  theme: ThemeMode;
}

/** Тіло у форматі експорту: без похідних даних (сил та сліду траєкторії). */
export type SceneBody = Omit<Body, 'force' | 'trail'>;

/** Корисне навантаження JSON-файлу сцени. Імпорт перевіряється за цією схемою. */
export interface SceneExportPayload {
  /** Версія схеми; змінюється при несумісних змінах формату. */
  schemaVersion: 1;
  /** Ідентифікатор застосунку-автора файлу. */
  app: 'physics-sim-frontend';
  /** Момент експорту, ISO 8601. */
  exportedAt: string;
  /** Обраний пресет. */
  presetId: PresetId;
  /** Параметри середовища. */
  environment: EnvironmentParams;
  /** Специфічні параметри пресету. */
  presetParams: PresetParams;
  /** Початкові тіла сцени. */
  bodies: SceneBody[];
}